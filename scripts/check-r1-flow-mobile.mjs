import { chromium, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const base='http://127.0.0.1:15262';
await mkdir('work/acceptance/r1-flow-mobile',{recursive:true});
const b=await chromium.launch({channel:'chrome',headless:true});
const ctx=await b.newContext({viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true,reducedMotion:'reduce'});
const p=await ctx.newPage(); const errors=[]; p.on('pageerror',e=>errors.push(e.message));
await p.goto(base+'/?quality=3&boot=0',{waitUntil:'domcontentloaded'});
await expect(p.locator('.app-shell')).toBeVisible({timeout:30000});
await p.waitForTimeout(1000);
await p.screenshot({path:'work/acceptance/r1-flow-mobile/01-hub.png'});
const entry=p.locator('a[href*="mission=r1"]').first();
await expect(entry).toBeVisible({timeout:15000});
await entry.click();
await expect(p.locator('[data-mission-step]')).toHaveAttribute('data-ready','true',{timeout:30000});
await p.getByTestId('action-accept').click();
await p.getByTestId('action-begin').click();
await p.getByTestId('point-switch').tap();
await expect(p.locator('.mission-kit')).toHaveAttribute('data-selected-point','switch');
await p.screenshot({path:'work/acceptance/r1-flow-mobile/02-mission.png'});
const overflow=await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
console.log(JSON.stringify({overflow,errors}));
await b.close();
